def get_settings(context=None):
    context = context or bpy.context
    return context.scene.marble_tools


def apply_preset(settings, key):
    data = PRESETS[key]
    for name, value in data.items():
        if name == "label":
            continue
        setattr(settings, name, value)


class MARBLE_OT_apply_preset(bpy.types.Operator):
    bl_idname = "marble.apply_preset"
    bl_label = "Apply Preset"
    bl_description = "Load the selected physics preset into the playtest and drop settings"
    bl_options = {"REGISTER", "UNDO"}

    def execute(self, context):
        settings = get_settings(context)
        apply_preset(settings, settings.preset)
        self.report({"INFO"}, f"Applied preset: {PRESETS[settings.preset]['label']}")
        return {"FINISHED"}


CLASSES = (MarbleToolsSettings, MARBLE_OT_apply_preset)


def register():
    for cls in CLASSES:
        bpy.utils.register_class(cls)
    bpy.types.Scene.marble_tools = PointerProperty(type=MarbleToolsSettings)


def unregister():
    del bpy.types.Scene.marble_tools
    for cls in reversed(CLASSES):
        bpy.utils.unregister_class(cls)
